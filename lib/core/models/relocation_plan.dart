/// Relocation Task item in a New to City Plan.
class PlanTask {
  final String id;
  final String title;
  final String description;
  final String category; // Used to deep-link to local providers/services
  final String phase; // 'Day 1 Essentials', 'Week 1', 'Utilities & Setup'
  final bool isCompleted;

  const PlanTask({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.phase,
    this.isCompleted = false,
  });

  factory PlanTask.fromMap(Map<String, dynamic> m) {
    return PlanTask(
      id: (m['id'] ?? '') as String,
      title: (m['title'] ?? '') as String,
      description: (m['description'] ?? '') as String,
      category: (m['category'] ?? 'Services') as String,
      phase: (m['phase'] ?? 'Day 1 Essentials') as String,
      isCompleted: (m['isCompleted'] ?? false) as bool,
    );
  }

  Map<String, dynamic> toMap() => {
        'id': id,
        'title': title,
        'description': description,
        'category': category,
        'phase': phase,
        'isCompleted': isCompleted,
      };

  PlanTask copyWith({
    String? id,
    String? title,
    String? description,
    String? category,
    String? phase,
    bool? isCompleted,
  }) {
    return PlanTask(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      category: category ?? this.category,
      phase: phase ?? this.phase,
      isCompleted: isCompleted ?? this.isCompleted,
    );
  }
}

/// Relocation Plan document (`plans/{planId}`).
/// Generated by Gemini AI based on destination locality, household profile, and timeline.
class RelocationPlan {
  final String id;
  final String userId;
  final String destinationArea;
  final String householdType;
  final List<PlanTask> tasks;
  final DateTime updatedAt;

  const RelocationPlan({
    required this.id,
    required this.userId,
    required this.destinationArea,
    required this.householdType,
    required this.tasks,
    required this.updatedAt,
  });

  int get totalTasks => tasks.length;
  int get completedTasks => tasks.where((t) => t.isCompleted).length;
  double get progress => totalTasks > 0 ? completedTasks / totalTasks : 0.0;

  factory RelocationPlan.fromMap(String id, Map<String, dynamic> m) {
    final rawTasks = m['tasks'] as List<dynamic>? ?? [];
    final parsedTasks = rawTasks
        .map((t) => PlanTask.fromMap(Map<String, dynamic>.from(t as Map)))
        .toList();

    return RelocationPlan(
      id: id,
      userId: (m['userId'] ?? '') as String,
      destinationArea: (m['destinationArea'] ?? 'Pune') as String,
      householdType: (m['householdType'] ?? 'General') as String,
      tasks: parsedTasks,
      updatedAt: m['updatedAt'] != null
          ? (m['updatedAt'] is DateTime
              ? m['updatedAt'] as DateTime
              : DateTime.tryParse(m['updatedAt'].toString()) ?? DateTime.now())
          : DateTime.now(),
    );
  }

  Map<String, dynamic> toMap() => {
        'userId': userId,
        'destinationArea': destinationArea,
        'householdType': householdType,
        'tasks': tasks.map((t) => t.toMap()).toList(),
        'updatedAt': updatedAt.toIso8601String(),
      };
}
